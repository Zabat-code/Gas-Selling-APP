export function translate(lang, key, vars = {}) {
  const dict = dictionaries[lang] || dictionaries.en
  let text = dict[key] ?? dictionaries.en[key] ?? key
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(`{${k}}`, v)
  }
  return text
}
